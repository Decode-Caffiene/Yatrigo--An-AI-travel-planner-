// Real airline logos by 2-letter IATA code, self-hosted in public/airlines/
// (downloaded once from Aviasales' CDN, which has correct logos for reused
// codes like U4/Buddha Air) so they load same-origin with no external CDN
// or image-optimizer round-trip. Returns null when no code is given so
// callers can skip rendering an image rather than showing a broken one.
export function airlineLogoUrl(code?: string | null): string | null {
  const trimmed = code?.trim().toUpperCase();
  if (!trimmed || trimmed.length !== 2) return null;
  if (NO_CDN_LOGO_CODES.has(trimmed)) return null;

  return `/airlines/${trimmed}.png`;
}

