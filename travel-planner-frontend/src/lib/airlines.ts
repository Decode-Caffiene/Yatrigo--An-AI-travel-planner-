/**
 * Instant search over airline names, IATA codes, and countries — "Qat" and
 * "QR" both find Qatar Airways, and "Nepal" lists Nepal's local carriers.
 * Name/code matches rank above country matches.
 */
export function searchAirlines(query: string, limit = 8): Airline[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const startsWith: Airline[] = [];
  const contains: Airline[] = [];
  const byCountry: Airline[] = [];

  for (const airline of AIRLINES) {
    const name = airline.name.toLowerCase();
    const code = airline.code.toLowerCase();
    const country = airline.country?.toLowerCase() ?? "";

    if (name.startsWith(q) || code === q) startsWith.push(airline);
    else if (name.includes(q)) contains.push(airline);
    else if (country.startsWith(q)) byCountry.push(airline);

    if (startsWith.length >= limit) break;
  }

  return [...startsWith, ...contains, ...byCountry].slice(0, limit);
}
